package nevavis.render;

import net.minecraft.client.gui.DrawContext;

/** Минималистичные пиксельные иконки 8x8, рисуются горизонтальными отрезками. */
public final class Icons {
	public static final int HOME = 0, VISUALS = 1, HUD = 2, MUSIC = 3, PARTICLES = 4, ANIMATIONS = 5,
			ENVIRONMENT = 6, CROSSHAIR = 7, THEMES = 8, PROFILES = 9, SETTINGS = 10, ABOUT = 11;

	private static final String[][] BITMAPS = {
			{"...##...", "..####..", ".######.", "########", ".##..##.", ".##..##.", ".######.", "........"},
			{"........", "..####..", ".##..##.", "##.##.##", "##.##.##", ".##..##.", "..####..", "........"},
			{"########", "#......#", "#.####.#", "#......#", "#.##.#.#", "#......#", "########", "........"},
			{"...####.", "...#..#.", "...#..#.", "...#....", ".###....", "####....", ".##.....", "........"},
			{"...#....", "...#....", ".#.#.#..", "..###...", "#######.", "..###...", ".#.#.#..", "...#...."},
			{"##......", "####....", "######..", "########", "######..", "####....", "##......", "........"},
			{"#..#..#.", ".#.##.#.", "..####..", "########", "..####..", ".#.##.#.", "#..#..#.", "........"},
			{"...##...", "...##...", "........", "##....##", "##....##", "........", "...##...", "...##..."},
			{"...##...", "..####..", ".######.", "########", "########", ".######.", "..####..", "........"},
			{"..####..", "..####..", "..####..", "...##...", ".######.", "########", "########", "........"},
			{".#.##.#.", "..####..", "##.##.##", ".######.", ".######.", "##.##.##", "..####..", ".#.##.#."},
			{"..####..", "..####..", "........", "..####..", "..####..", "..####..", "..####..", "........"}
	};

	private Icons() {
	}

	public static void draw(DrawContext c, int icon, int x, int y, int color) {
		String[] rows = BITMAPS[icon];
		for (int j = 0; j < 8; j++) {
			String row = rows[j];
			int i = 0;
			while (i < 8) {
				if (row.charAt(i) == '#') {
					int start = i;
					while (i < 8 && row.charAt(i) == '#') {
						i++;
					}
					Gfx.fill(c, x + start, y + j, x + i, y + j + 1, color);
				} else {
					i++;
				}
			}
		}
	}
}
